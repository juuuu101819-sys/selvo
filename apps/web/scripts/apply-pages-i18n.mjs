function deepMerge(target, source) {
  for (const [key, value] of Object.entries(source)) {
    if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
      target[key] = target[key] ?? {};
      deepMerge(target[key], value);
    } else {
      target[key] = value;
    }
  }
}

function flatten(value, prefix = '') {
  if (typeof value !== 'object' || value === null) {
    return prefix === '' ? [] : [prefix];
  }
  return Object.entries(value).flatMap(([key, child]) =>
    flatten(child, prefix === '' ? key : `${prefix}.${key}`),
  );
}

for (const locale of LOCALES) {
  const path = join(messagesDir, `${locale}.json`);
  const catalog = JSON.parse(readFileSync(path, 'utf8'));
  const patch = PATCHES[locale];
  if (!patch) {
    console.error(`Missing patch for ${locale}`);
    process.exit(1);
  }
  const before = flatten(catalog).length;
  deepMerge(catalog.footer, patch.footer);
  deepMerge(catalog.pages, patch.pages);
  const after = flatten(catalog).length;
  writeFileSync(path, `${JSON.stringify(catalog, null, 2)}\n`);
  console.log(`patched pages for ${locale} (${before} → ${after} keys)`);
}

